export type IconName = keyof typeof SOURCES;

/** Inner markup of a lucide icon, without its outer `<svg>` element. */
export function iconMarkup(name: string): string {
  const source = (SOURCES as Record<string, string | undefined>)[name];

  if (!source) {
    throw new Error(`Unknown icon: ${name}. Add it to docs/.vitepress/theme/icons.ts.`);
  }

  return source.replace(/^[\s\S]*?<svg[^>]*>/, "").replace(/<\/svg>\s*$/, "").trim();
}
