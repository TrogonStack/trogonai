use std::time::{Duration, SystemTime};

use base64::Engine as _;
use base64::engine::general_purpose::STANDARD as B64;
use ed25519_dalek::{Signer as _, SigningKey};
use serde_json::Value;
use trogon_sandbox_contract::{DispatchAttemptId, DispatchAuth, LeaseEpoch, LeaseId, TenantId, WorkerId};

use crate::dispatch_auth_constants::{
    AUTH_FIELD, DEFAULT_TTL, ENV_SIGNING_KEY, ENV_SIGNING_KEY_FILE, ENV_SIGNING_KEY_ID, ENV_SIGNING_TTL_SECS,
};
use crate::dispatch_envelope::{body_digest, pointer_str, signing_input, string_at, unix};
use crate::{DispatchSignError, DispatchSignerConfigError};

/// The broker's signing half.
pub struct DispatchSigner {
    pub(crate) key_id: String,
    pub(crate) key: SigningKey,
    pub(crate) ttl: Duration,
}

impl DispatchSigner {
    /// A signer for the Ed25519 `seed`, whose envelopes name `key_id`.
    pub fn new(key_id: impl Into<String>, seed: [u8; 32]) -> Self {
        Self {
            key_id: key_id.into(),
            key: SigningKey::from_bytes(&seed),
            ttl: DEFAULT_TTL,
        }
    }

    /// Sets how long a signed envelope stays valid.
    pub fn with_ttl(mut self, ttl: Duration) -> Self {
        self.ttl = ttl;
        self
    }

    /// The key id workers look the public key up by.
    pub fn key_id(&self) -> &str {
        &self.key_id
    }

    /// The public key to hand to workers, base64.
    pub fn public_key_b64(&self) -> String {
        B64.encode(self.key.verifying_key().to_bytes())
    }

    /// A fresh random key as `(base64 seed, base64 public key)`, for a throwaway local stack. Production keys are
    /// generated by the operator.
    pub fn generate_keypair_b64() -> (String, String) {
        let mut seed = [0u8; 32];
        seed[..16].copy_from_slice(uuid::Uuid::new_v4().as_bytes());
        seed[16..].copy_from_slice(uuid::Uuid::new_v4().as_bytes());
        let signer = Self::new("k1", seed);
        (B64.encode(seed), signer.public_key_b64())
    }

    /// Reads the signer from the process environment; `Ok(None)` when no key is set.
    pub fn from_env() -> Result<Option<Self>, DispatchSignerConfigError> {
        Self::from_lookup(&|name| std::env::var(name).ok())
    }

    /// Reads the signer from the variables `lookup` returns; `Ok(None)` when no key is set.
    pub fn from_lookup(lookup: &dyn Fn(&str) -> Option<String>) -> Result<Option<Self>, DispatchSignerConfigError> {
        let seed = match lookup(ENV_SIGNING_KEY_FILE) {
            Some(path) if !path.is_empty() => std::fs::read_to_string(&path)
                .map_err(|source| DispatchSignerConfigError::ReadKeyFile { path, source })?,
            _ => match lookup(ENV_SIGNING_KEY) {
                Some(value) if !value.is_empty() => value,
                _ => return Ok(None),
            },
        };
        let seed = B64
            .decode(seed.trim())
            .ok()
            .and_then(|bytes| <[u8; 32]>::try_from(bytes).ok())
            .ok_or(DispatchSignerConfigError::InvalidSeed)?;
        let key_id = lookup(ENV_SIGNING_KEY_ID)
            .filter(|id| !id.is_empty())
            .unwrap_or_else(|| "k1".to_owned());
        if key_id.contains([':', ',', '\n']) {
            return Err(DispatchSignerConfigError::InvalidKeyId);
        }
        let mut signer = Self::new(key_id, seed);
        if let Some(secs) = lookup(ENV_SIGNING_TTL_SECS) {
            let secs = secs
                .parse::<u64>()
                .ok()
                .filter(|secs| *secs > 0)
                .ok_or(DispatchSignerConfigError::InvalidTtl)?;
            signer.ttl = Duration::from_secs(secs);
        }
        Ok(Some(signer))
    }

    /// Signs `auth` in place: sets its signature over the other fields.
    pub(crate) fn seal(&self, auth: &mut DispatchAuth) {
        auth.signature = B64.encode(self.key.sign(&signing_input(auth)).to_bytes());
    }

    /// Adds a fresh envelope to a dispatch JSON body. Any envelope already in the body is replaced, so a stored
    /// dispatch can be re-signed on re-send.
    pub fn sign_payload(&self, payload: &[u8], operation: &str) -> Result<Vec<u8>, DispatchSignError> {
        self.sign_payload_at(payload, operation, SystemTime::now())
    }

    /// [`sign_payload`](Self::sign_payload) as of `now`.
    pub fn sign_payload_at(
        &self,
        payload: &[u8],
        operation: &str,
        now: SystemTime,
    ) -> Result<Vec<u8>, DispatchSignError> {
        let mut value: Value = serde_json::from_slice(payload).map_err(DispatchSignError::NotJson)?;
        let tenant = string_at(&value, "/request/tenant").ok_or(DispatchSignError::MissingTenant)?;
        let tenant = TenantId::new(tenant).map_err(DispatchSignError::InvalidTenant)?;
        let lease_id = string_at(&value, "/lease_id").ok_or(DispatchSignError::MissingLease)?;
        let worker_id = pointer_str(&value, "/target/worker_id")
            .map(WorkerId::new)
            .transpose()
            .map_err(DispatchSignError::InvalidWorker)?;
        let attempt_id = pointer_str(&value, "/target/attempt_id")
            .map(DispatchAttemptId::new)
            .transpose()
            .map_err(DispatchSignError::InvalidAttempt)?;
        let epoch = value
            .pointer("/target/epoch")
            .and_then(Value::as_u64)
            .map(LeaseEpoch::new)
            .transpose()
            .map_err(DispatchSignError::InvalidEpoch)?;
        let object = value.as_object_mut().ok_or(DispatchSignError::NotObject)?;
        object.remove(AUTH_FIELD);
        let body_sha256 = sha256_digest_of_object(object)?;
        let mut auth = DispatchAuth {
            version: 1,
            key_id: self.key_id.clone(),
            operation: operation.to_owned(),
            tenant,
            lease_id: LeaseId::new(lease_id),
            worker_id,
            attempt_id,
            nonce: None,
            epoch,
            expires_at: unix(now + self.ttl),
            body_sha256,
            signature: String::new(),
        };
        self.seal(&mut auth);
        object.insert(
            AUTH_FIELD.to_owned(),
            serde_json::to_value(&auth).map_err(DispatchSignError::Encode)?,
        );
        serde_json::to_vec(&value).map_err(DispatchSignError::Encode)
    }
}

fn sha256_digest_of_object(
    object: &serde_json::Map<String, Value>,
) -> Result<trogon_sandbox_contract::FileSha256, DispatchSignError> {
    trogon_sandbox_contract::FileSha256::new(body_digest(object)).map_err(DispatchSignError::Digest)
}
