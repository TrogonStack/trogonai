//! The host side of the Windows network fence.
//!
//! The fence blocks network egress on Windows with a dedicated local account and
//! machine-wide Windows Filtering Platform filters, both written by an
//! elevated install. This crate drives that install and the checks around it
//! through the fence helper executable and builds the argv of a launch under the
//! account. It is platform neutral: it only spawns the helper executable it is
//! given, so everything but that executable runs and is tested on any host.

